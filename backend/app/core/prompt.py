LANGUAGE_NAMES = {"zh": "简体中文", "en": "English"}

STYLE_HINTS = {
    "concise": "控制在 400 到 600 字。先给结论，再讲一到两个关键依据，最后给一到两个能马上做的动作。不要为了凑结构分很多小标题。",
    "detailed": "可以写到 800 到 1200 字。按用户选的方向展开，每一节先结论后依据。不要重复同一观点。",
}


def build_messages(
    system: str,
    chart_text: str,
    chart_json: str,
    question: str | None = None,
    style: str = "concise",
    focus: list[str] | None = None,
    lang: str = "zh",
) -> list[dict[str, str]]:
    language = LANGUAGE_NAMES.get(lang, LANGUAGE_NAMES["zh"])
    parts = [
        f"体系：{system}",
        "",
        "## 排盘规范文本",
        chart_text.strip(),
        "",
        "## 结构化数据（供你引用，不要复述整段 JSON）",
        chart_json,
    ]
    hint = SYSTEM_HINTS.get(system)
    if hint:
        parts += ["", "## 这个体系怎么讲", hint]
    if focus:
        parts += [
            "",
            "## 解读重点",
            "用户选择了这些方向：" + "、".join(focus),
            "请按上面的顺序组织小标题，每个方向都先引用对应盘面证据，再给出解读；"
            "未选中的方向只在确有盘面依据时用一句话带过。开头用两三句话交代整体格局。",
        ]
    if question:
        parts += ["", "## 用户问题", question.strip()]
    elif focus:
        parts += ["", "## 用户问题", "请围绕上述重点解读这张盘。"]
    else:
        parts += ["", "## 用户问题", "请对这张盘做一个整体解读。"]
    parts += ["", "## 表达要求", STYLE_HINTS.get(style, STYLE_HINTS["concise"])]
    return [
        {"role": "system", "content": SYSTEM_PROMPT.format(language=language)},
        {"role": "user", "content": "\n".join(parts)},
    ]
