def _build_deck() -> list[Card]:
    cards: list[Card] = [
        Card(name=name, arcana="major", suit="", upright=up, reversed=rev)
        for name, up, rev in _MAJOR
    ]
    for suit, (_element, theme) in _SUITS.items():
        for rank in _RANK_NAMES:
            upright = f"{theme}·{_RANK_THEME[rank]}"
            reversed = f"{theme}受阻，{_RANK_SHADOW[rank]}"
            cards.append(
                Card(name=f"{suit}{rank}", arcana="minor", suit=suit, upright=upright, reversed=reversed)
            )
    return cards


DECK: list[Card] = _build_deck()
