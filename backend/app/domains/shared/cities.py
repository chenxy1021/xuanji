CITIES: list[Place] = [
    Place(name=name, province=province, longitude=lon, latitude=lat, timezone=8.0)
    for name, province, lon, lat in _RAW
] + [
    Place(name=name, province=province, longitude=lon, latitude=lat, timezone=tz)
    for name, province, lon, lat, tz, _aliases in _WORLD
]

DEFAULT_PLACE = CITIES[0]

# 名称 → 检索用别名（含英文名；英文匹配大小写不敏感）
_ALIASES: dict[str, tuple[str, ...]] = {name: aliases for name, _, _, _, _, aliases in _WORLD}


def _haystack(city: Place) -> str:
    parts = [city.name, city.province, *_ALIASES.get(city.name, ())]
    return " ".join(parts).lower()


_INDEX: list[tuple[Place, str]] = [(city, _haystack(city)) for city in CITIES]


def search_cities(query: str = "", limit: int = 20) -> list[Place]:
    """按中文名 / 省份国家 / 英文别名检索城市，空查询返回默认顺序的前若干个。"""
    q = (query or "").strip()
    if not q:
        return CITIES[:limit]
    needle = q.lower()
    # 去掉「市」再比对，输入「北京」也能命中「北京市」
    q_stripped = q.rstrip("市").lower()
    hits = [
        city
        for city, haystack in _INDEX
        if needle in haystack or (q_stripped and q_stripped in haystack)
    ]
    return hits[:limit]


def find_city(name: str) -> Place | None:
    """按名称精确取城市（含英文别名，大小写不敏感）。"""
    needle = (name or "").strip().lower()
    if not needle:
        return None
    for city, _ in _INDEX:
        if city.name.lower() == needle:
            return city
    for city, haystack in _INDEX:
        if needle in haystack:
            return city
    return None
